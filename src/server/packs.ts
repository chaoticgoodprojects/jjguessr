import type { Song } from "../rules";

/**
 * Built-in song lists, standing in for Spotify's editorial playlists (which
 * apps can no longer read). Each row is [title, artist, album], written the
 * way Spotify lists them. Edit freely; every pack needs at least 20 songs.
 */
export interface Pack {
  id: string;
  name: string;
  songs: Song[];
}

type Row = [title: string, artist: string, album: string];

function pack(id: string, name: string, rows: Row[]): Pack {
  return { id, name, songs: rows.map(([title, artist, album], i) => ({ id: `${id}-${i + 1}`, title, artist, album })) };
}

